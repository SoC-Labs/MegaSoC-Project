#!/usr/bin/env python3
"""rom_init_gen.py DUMP OLD_ROM.v NEW_ROM.v OUT_DIR   (build 65, 24 Nov 2026)

The boot ROM of the HAPS-SX build is 32 RAMB36E2 in 16K x 2 mode (u_bootrom/RDATA_reg_0..31). This script
 1. reads the INIT strings dumped from the routed build-64 checkpoint (dump_rom64.tcl) and PROVES how the ROM words are
    laid out in them: every bit lane of every block RAM must equal exactly one data bit of OLD_ROM.v at all 16,384
    addresses, and the 64 lanes must cover the 64 data bits once each (any other outcome is a hard error);
 2. writes the same layout for NEW_ROM.v as Tcl (rom65_init.tcl: set_property INIT_xx on the same cells) and as a
    plain expected-value file (rom65_expected.txt) for the read-back check in patch_rom65.tcl."""
import re, sys
dump, old_v, new_v, out = sys.argv[1:5]
DEPTH = 16384
def rom_words(vfile):
    w = [0] * DEPTH; n = 0
    for ln in open(vfile):
        m = re.search(r"14'h([0-9a-f]+) : RDATA <= 64'h([0-9a-f]+);", ln)
        if m: w[int(m.group(1), 16)] = int(m.group(2), 16); n += 1
    return w, n
old, n_old = rom_words(old_v); new, n_new = rom_words(new_v)
print("old ROM: %d words defined, new ROM: %d words defined, %d words differ" % (n_old, n_new, sum(1 for a in range(DEPTH) if old[a] != new[a])))
cells, cur = [], None
for ln in open(dump):
    ln = ln.rstrip("\n"); f = ln.split(" ")
    if f[0] == "CELL": cur = {"name": f[1], "ref": f[3], "loc": f[5], "prop": {}, "out": {}, "in": {}, "init": {}}; cells.append(cur)
    elif f[0] == "PROP": cur["prop"][f[1]] = " ".join(f[2:])
    elif f[0] == "OUT": cur["out"][f[1]] = f[2]
    elif f[0] == "IN": cur["in"][f[1]] = " ".join(f[2:])
    elif re.match(r"INITP?_[0-9A-F]{2}$", f[0]): cur["init"][f[0]] = f[1]
print("block RAM cells in the dump: %d" % len(cells))
if len(cells) != 32: sys.exit("ERROR: expected 32 cells")
def init_int(c):
    v = 0
    for i in range(128):
        s = c["init"]["INIT_%02X" % i]; m = re.match(r"256'h([0-9A-Fa-f]{64})$", s)
        if not m: sys.exit("ERROR: unexpected INIT format in %s: %s" % (c["name"], s[:40]))
        v |= int(m.group(1), 16) << (256 * i)
    return v
def lane(v, k):                       # bit k (0/1) of the 2-bit word at every address, as one big integer
    r = 0
    for a in range(DEPTH):
        if (v >> (2 * a + k)) & 1: r |= 1 << a
    return r
def col(words, b):
    r = 0
    for a in range(DEPTH):
        if (words[a] >> b) & 1: r |= 1 << a
    return r
old_cols = {col(old, b): b for b in range(64)}
if len(old_cols) != 64: sys.exit("ERROR: two data bit columns of the old ROM are identical; the layout cannot be proven this way")
used, layout, problems = {}, [], 0
for c in cells:
    for p in ("READ_WIDTH_A",):
        if c["prop"].get(p) != "2": sys.exit("ERROR: %s %s = %s, expected 2" % (c["name"], p, c["prop"].get(p)))
    for i in range(16):
        if not re.match(r"256'h0{64}$", c["init"]["INITP_%02X" % i]): sys.exit("ERROR: %s has non-zero INITP" % c["name"])
    v = init_int(c); bits = []
    for k in (0, 1):
        b = old_cols.get(lane(v, k))
        if b is None: print("ERROR: %s lane %d matches no data bit of the old ROM" % (c["name"], k)); problems += 1
        elif b in used: print("ERROR: data bit %d found twice (%s and %s)" % (b, used[b], c["name"])); problems += 1
        else: used[b] = c["name"]
        bits.append(b)
    net = [c["out"].get("DOUTADOUT[%d]" % k, "?") for k in (0, 1)]
    layout.append((c, bits))
    short = c["name"].split("/")[-1]
    print("  %-13s %-15s lane0 = RDATA[%s]  lane1 = RDATA[%s]   nets: %s , %s" % (short, c["loc"], bits[0], bits[1], net[0].split("/")[-1], net[1].split("/")[-1]))
    for k in (0, 1):
        m = re.search(r"RDATA\[(\d+)\]", net[k])
        if m and bits[k] is not None and int(m.group(1)) != bits[k]: print("ERROR: %s lane %d: net says RDATA[%s], contents say RDATA[%d]" % (short, k, m.group(1), bits[k])); problems += 1
if problems or sorted(used) != list(range(64)): sys.exit("ERROR: layout not proven (%d problems, %d of 64 data bits located)" % (problems, len(used)))
print("LAYOUT PROVEN: 64 lanes = 64 data bits, exact at all %d addresses" % DEPTH)
# ---- new contents, same layout ----
tcl = open(out + "/rom65_init.tcl", "w"); exp = open(out + "/rom65_expected.txt", "w"); changed = 0
tcl.write("# generated by rom_init_gen.py: boot ROM = %s\n" % new_v)
for c, bits in layout:
    v = 0
    for a in range(DEPTH):
        w = new[a]; v |= (((w >> bits[0]) & 1) | (((w >> bits[1]) & 1) << 1)) << (2 * a)
    assert lane(v, 0) == col(new, bits[0]) and lane(v, 1) == col(new, bits[1])
    for i in range(128):
        k = "INIT_%02X" % i; s = "256'h%064X" % ((v >> (256 * i)) & ((1 << 256) - 1))
        exp.write("%s %s %s\n" % (c["name"], k, s))
        if s.upper() != c["init"][k].upper(): tcl.write("set_property %s {%s} [get_cells {%s}]\n" % (k, s, c["name"])); changed += 1
tcl.close(); exp.close()
print("rom65_init.tcl: %d INIT strings change (of %d); rom65_expected.txt written" % (changed, 32 * 128))
